/** Builds src/data/seo/local-pages.raw.js from local-places.raw.txt × 4 keywords */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SEO_KEYWORDS } from "../src/data/seo/keywords.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rawPath = path.join(root, "src", "data", "seo", "local-places.raw.txt");
const outPath = path.join(root, "src", "data", "seo", "local-pages.raw.js");

function parseGroups(text) {
  const groups = [];
  let current = null;
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    if (trimmed.startsWith("#")) {
      current = { region: trimmed.replace(/^#\s*/, ""), places: [] };
      groups.push(current);
      continue;
    }
    if (!current) {
      current = { region: "전국", places: [] };
      groups.push(current);
    }
    current.places.push(trimmed);
  }
  return groups;
}

function makeScope(region, place, used) {
  let scope = place;
  if (used.has(scope)) {
    const short = region.split(/[·\s]/)[0] || region;
    scope = `${place}·${short}`;
  }
  if (used.has(scope)) {
    let n = 2;
    while (used.has(`${scope}${n}`)) n += 1;
    scope = `${scope}${n}`;
  }
  used.add(scope);
  return scope;
}

const groups = parseGroups(fs.readFileSync(rawPath, "utf8"));
const usedScopes = new Set();
const pages = [];
let seq = 1;

for (const group of groups) {
  for (const place of group.places) {
    for (const kw of SEO_KEYWORDS) {
      const scope = makeScope(group.region, place, usedScopes);
      const title = `${place} ${kw.label}`;
      pages.push({
        kind: "local",
        id: `L${String(seq).padStart(5, "0")}`,
        keyword: kw.slug,
        scope,
        placeLabel: place,
        regionGroup: group.region,
        title,
        petType: kw.petType,
        free: Boolean(kw.free),
      });
      seq += 1;
    }
  }
}

const body = `// AUTO-GENERATED by scripts/build-local-seo-source.mjs — do not edit by hand
export const LOCAL_SEO_PAGES_RAW = ${JSON.stringify(pages, null, 2)};
`;
fs.writeFileSync(outPath, body, "utf8");
console.log(`local SEO pages: ${pages.length} (${groups.length} regions, ${usedScopes.size} unique scopes)`);
